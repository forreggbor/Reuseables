    /**
     * Build a complete standalone <svg> element for the named icon.
     *
     * Returns an empty string for an unknown name instead of throwing —
     * this renders inside an admin page during a live patch install, and
     * an exception here would white-screen the operator mid-upgrade. The
     * gap is still visible (a missing icon, not a missing feature) and is
     * logged so it does not go unnoticed during development.
     *
     * @param string $name       Icon name, e.g. "check-circle-fill"
     * @param string $extraClass Additional CSS class(es) appended after "patch-icon"
     * @return string            HTML for a self-contained <svg>, or '' if $name is unknown
     */
    public static function svg(string $name, string $extraClass = ''): string
    {
        if (!isset(self::PATHS[$name])) {
            error_log("PatchIcon: unknown icon name '{$name}'");
            return '';
        }

        $class = 'patch-icon' . ($extraClass !== '' ? ' ' . $extraClass : '');

        return '<svg class="' . htmlspecialchars($class, ENT_QUOTES) . '" viewBox="0 0 16 16" '
            . 'aria-hidden="true" focusable="false">' . self::PATHS[$name] . '</svg>';
    }

    /**
     * Build a name => full <svg> markup map for a set of icons, ready to be
     * JSON-encoded into a data-icons attribute for client-side JS to read
     * without holding its own copy of the path data.
     *
     * @param string[] $names Icon names to include
     * @return array<string, string> name => <svg> markup (unknown names omitted)
     */
    public static function map(array $names): array
    {
        $result = [];
        foreach ($names as $name) {
            $svg = self::svg($name);
            if ($svg !== '') {
                $result[$name] = $svg;
            }
        }

        return $result;
    }

    /**
     * List every known icon name.
     *
     * @return string[]
     */
    public static function names(): array
    {
        return array_keys(self::PATHS);
    }

    /**
     * Check whether an icon name is known.
     *
     * @param string $name Icon name to check
     * @return bool
     */
    public static function has(string $name): bool
    {
        return isset(self::PATHS[$name]);
    }
